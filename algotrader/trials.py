"""Project-wide count of configurations tried, for one honest luck bar (roadmap M2).

Every grid point of every experiment on every universe is a try: core and broad
(`experiments.py`), the long history (`longrun.py`, with the stop-loss test in
`results/long_stop`), the mid-cap test (`results/mid`) and merger arbitrage (`results/merger`). Bailey & Lopez de Prado's
expected maximum Sharpe of that many zero-edge tries is reported for each test length.
Writes `results/trials.md`.

Example:
    python -m algotrader.trials
"""
import argparse
import json
from pathlib import Path

from .stats import expected_max_sharpe

SOURCES = {"core": "results/manifest.json", "broad": "results/broad/manifest.json",
           "long": "results/long/manifest.json", "long_stop": "results/long_stop/manifest.json",
           "long_conc": "results/long_conc/manifest.json", "long_rebal": "results/long_rebal/manifest.json",
           "long_vol": "results/long_vol/manifest.json",
           "mid": "results/mid/manifest.json", "merger": "results/merger/manifest.json"}


def count(sources=SOURCES) -> dict:
    """{source: (experiments, configurations)} from each manifest that exists."""
    from . import experiments, longrun
    out = {}
    for name, path in sources.items():
        p = Path(path)
        if not p.exists():
            continue
        man = json.loads(p.read_text())
        if name.startswith("long") or name in ("mid", "merger"):      # manifests that store their grid size
            n = sum(v["configurations"] for v in man.values())
        else:
            n = sum(len(experiments.BY_NAME[k].combos()) for k in man if k in experiments.BY_NAME)
        out[name] = (len(man), n)
    return out


def report(sources=SOURCES, long_years=None) -> str:
    counts = count(sources)
    total = sum(n for _, n in counts.values())
    lines = ["# Configurations tried", "",
             "Generated by `python -m algotrader.trials`; do not edit by hand. Every grid point "
             "of every experiment on every universe counts as one try (Bailey & Lopez de Prado "
             "2014: the best of N zero-edge strategies has an expected Sharpe of about the bar "
             "below).", "",
             "| Source | Experiments | Configurations |", "|---|---|---|"]
    lines += [f"| {k} | {e} | {n} |" for k, (e, n) in counts.items()]
    lines += [f"| **total** | {sum(e for e, _ in counts.values())} | **{total}** |", "",
              "| Test length | Luck bar for all configurations |", "|---|---|"]
    for years in sorted({3.3} | ({long_years} if long_years else set())):
        lines.append(f"| {years:.1f} years | {expected_max_sharpe(total, years):.2f} |")
    return "\n".join(lines) + "\n"


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--long-years", type=float, default=None,
                   help="length of the long-history test (default: from results/long)")
    p.add_argument("--out", default="results/trials.md")
    args = p.parse_args(argv)
    years = args.long_years
    wf = sorted(Path("results/long").glob("*_wf_returns.csv"))
    if years is None and wf:
        import pandas as pd
        years = len(pd.read_csv(wf[0], index_col=0)) / 252
    text = report(long_years=years)
    Path(args.out).write_text(text)
    print(text)


if __name__ == "__main__":
    main()
