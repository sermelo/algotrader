"""How deep a drawdown to be prepared for: block-bootstrap bounds on the maximum drawdown.

A backtest shows one maximum drawdown, the one its particular sequence of days produced. Reordering
the same days in 20-day blocks (circular block bootstrap, as `stats.sharpe_interval`; blocks keep
volatility clustering) gives the range of drawdowns that returns like these could have produced:
the bound at level 95% is a drawdown that only 5% of the resampled histories exceed. Reported over the
whole test period and over one year (252 days), the latter being what a holder sees in a bad year.

The bounds assume the future draws from the same days. Blocks of 20 days cannot rebuild a crisis that
unfolds over many months, so a 2008-style slide can exceed them. For the same reason they are harsh on
strategies whose point is timing (a trend filter that steps aside in long declines): reordering the days
breaks the timing that kept their realised drawdown small.

Separate from the runners (like `french.py`): it reads the committed walk-forward returns and no
experiment's fingerprint includes it.

    python -m algotrader.drawdown            # results/, results/broad, results/long, results/mid -> drawdown.md
    python -m algotrader.drawdown --results results/long
"""
import argparse
import math
from pathlib import Path

import numpy as np
import pandas as pd

LEVELS = (0.90, 0.95, 0.975)
YEAR = 252
DIRS = ("results", "results/broad", "results/long", "results/mid")


def max_drawdown(r: np.ndarray) -> float:
    """Maximum drawdown (<= 0) of the equity curve that compounds daily returns `r`, starting at 1."""
    eq = np.cumprod(1 + np.asarray(r, dtype=float))
    peak = np.maximum.accumulate(np.concatenate([[1.0], eq]))[1:]
    return float(min(0.0, (eq / peak - 1).min())) if len(eq) else float("nan")


def drawdown_bounds(r: pd.Series, levels=LEVELS, horizon: int = None, block: int = 20,
                    n: int = 1000, seed: int = 0) -> dict:
    """Circular block-bootstrap distribution of the maximum drawdown over `horizon` days (default: the
    series' length). Returns the median and, for each level q, the drawdown exceeded (deeper) in only
    1 - q of the resampled paths. NaN if there are fewer than two blocks of data."""
    x = pd.Series(r).dropna().to_numpy()
    h = horizon or len(x)
    out = {"median": float("nan")} | {q: float("nan") for q in levels}
    if len(x) < 2 * block or h < 1:
        return out
    rng = np.random.default_rng(seed)
    nblocks = math.ceil(h / block)
    dd = np.empty(n)
    for i in range(n):
        starts = rng.integers(0, len(x), nblocks)
        idx = (starts[:, None] + np.arange(block)[None, :]).ravel()[:h] % len(x)
        dd[i] = max_drawdown(x[idx])
    out["median"] = float(np.median(dd))
    for q in levels:
        out[q] = float(np.quantile(dd, 1 - q))
    return out


def table(returns: dict, levels=LEVELS) -> pd.DataFrame:
    """One row per return series: realised drawdown, full-period and one-year bounds."""
    rows = []
    for name, r in returns.items():
        r = pd.Series(r).dropna()
        full, year = drawdown_bounds(r, levels), drawdown_bounds(r, levels, horizon=YEAR)
        rows.append({"experiment": name, "years": len(r) / YEAR, "realised": max_drawdown(r.to_numpy()),
                     "median": full["median"]} | {f"full_{q:g}": full[q] for q in levels}
                    | {"year_median": year["median"]} | {f"year_{q:g}": year[q] for q in levels})
    return pd.DataFrame(rows).set_index("experiment") if rows else pd.DataFrame()


def read_returns(results_dir, column="base") -> dict:
    """The `column` walk-forward returns of each `*_wf_returns.csv`, plus `buy_and_hold` from `hold`."""
    out, hold = {}, None
    for path in sorted(Path(results_dir).glob("*_wf_returns.csv")):
        wf = pd.read_csv(path, index_col=0, parse_dates=True)
        out[path.name.removesuffix("_wf_returns.csv")] = wf[column]
        if hold is None and "hold" in wf:
            hold = wf["hold"]
    if hold is not None:
        out["buy_and_hold"] = hold
    return out


def write_report(results_dir, levels=LEVELS) -> Path:
    t = table(read_returns(results_dir), levels).sort_values(f"full_{levels[1]:g}", ascending=False)
    qs = " / ".join(f"{q:.1%}" for q in levels)
    lines = [
        f"# Drawdown bounds ({results_dir})", "",
        "Generated by `python -m algotrader.drawdown`; do not edit by hand. Walk-forward returns at base costs. "
        "Realised = the backtest's own maximum drawdown. The other columns reorder the same days in 20-day blocks "
        "(1,000 circular block-bootstrap paths, seed 0): median, and the drawdown only 10% / 5% / 2.5% of paths exceed, "
        "over the whole test period and over one year (252 days). A crisis lasting many months can exceed them; "
        "for timing strategies (trend filters) the reordering also breaks the timing, so their bounds are too deep.", "",
        f"| Experiment | Years | Realised | Median | Whole period {qs} | One year: median | One year {qs} |",
        "|---|---|---|---|---|---|---|"]
    for name, r in t.iterrows():
        full = " / ".join(f"{r[f'full_{q:g}']:.1%}" for q in levels)
        year = " / ".join(f"{r[f'year_{q:g}']:.1%}" for q in levels)
        lines.append(f"| `{name}` | {r['years']:.1f} | {r['realised']:.1%} | {r['median']:.1%} | {full} | "
                     f"{r['year_median']:.1%} | {year} |")
    path = Path(results_dir) / "drawdown.md"
    path.write_text("\n".join(lines) + "\n")
    return path


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--results", nargs="*", default=list(DIRS))
    a = p.parse_args(argv)
    for d in a.results:
        if any(Path(d).glob("*_wf_returns.csv")):
            print(write_report(d))


if __name__ == "__main__":
    main()
