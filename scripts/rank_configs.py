"""Rank every long-history configuration by return and by Sharpe -> results/ranking.md.

Reads the committed daily returns (base costs) of the long-history tests (2012-01-01 on): the
walk-forward results (`results/long/*_wf_returns.csv`), the concentration, weekly and volatile-subset
tests. Every number is a backtest chosen after the fact from 1,226 tries: the best of them are the
luckiest as much as the best (see the luck bar in `results/trials.md`).

    uv run python scripts/rank_configs.py
"""
import json
from pathlib import Path

import pandas as pd

from algotrader.stats import returns_stats, sharpe_interval

START = "2012-01-01"
SOURCES = {"long_conc": "results/long_conc/returns.csv", "long_rebal": "results/long_rebal/returns.csv",
           "long_vol": "results/long_vol/returns.csv"}
PAPER = Path("config/paper.json")


def collect() -> pd.DataFrame:
    series = {}
    for src, path in SOURCES.items():
        df = pd.read_csv(path, index_col=0, parse_dates=True)
        for c in df.columns:
            if c.endswith("|base"):
                series.setdefault(c[:-5], (src, df[c]))
    for path in sorted(Path("results/long").glob("*_wf_returns.csv")):
        df = pd.read_csv(path, index_col=0, parse_dates=True)
        if "base" in df:
            series.setdefault(path.name.replace("_wf_returns.csv", " (walk-forward)"), ("long", df["base"]))
    rows = []
    for name, (src, r) in series.items():
        r = r[r.index >= START].dropna()
        if len(r) < 252 * 10:
            continue
        st = returns_stats(r)
        lo, hi = sharpe_interval(r)
        rows.append({"configuration": name, "source": src, "cagr": st["cagr"], "sharpe": st["sharpe"],
                     "lo": lo, "hi": hi, "max_dd": st["max_drawdown"], "vol": r.std() * 252 ** 0.5})
    return pd.DataFrame(rows).drop_duplicates(["cagr", "sharpe", "max_dd"])


def table(df: pd.DataFrame, n=15) -> str:
    lines = ["| # | Configuration | Test | CAGR | Per month | Sharpe [90% CI] | Volatility | Max drawdown |",
             "|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(df.head(n).itertuples(), 1):
        lines.append(f"| {i} | `{r.configuration}` | {r.source} | {r.cagr:+.1%} | {(1 + r.cagr) ** (1 / 12) - 1:+.2%} | "
                     f"{r.sharpe:.2f} [{r.lo:.2f}, {r.hi:.2f}] | {r.vol:.1%} | {r.max_dd:.1%} |")
    return "\n".join(lines)


def main():
    df = collect()
    spy = pd.read_csv(SOURCES["long_conc"], index_col=0, parse_dates=True)["SPY"]
    spy = returns_stats(spy[spy.index >= START].dropna())
    cfg = json.loads(PAPER.read_text())
    paper = {"operating_profitability": "op_profitability"}.get(cfg["signal"], cfg["signal"])
    chosen = df[df["configuration"] == f"{paper}|top{cfg['top_n']}"]
    end = pd.read_csv(SOURCES["long_vol"], index_col=0, parse_dates=True).index.max().date()
    text = f"""# Ranking of the long-history configurations

Generated by `scripts/rank_configs.py`; do not edit by hand. Point-in-time S&P 500, $1M, IBKR commission +
2 bp half-spread, {START} to {end}, daily returns of every configuration in the concentration, weekly,
volatile-subset tests and the long walk-forward ({len(df)} distinct series). SPY over the same days:
CAGR {spy['cagr']:+.1%} ({(1 + spy['cagr']) ** (1 / 12) - 1:+.2%} a month), Sharpe {spy['sharpe']:.2f}, max drawdown
{spy['max_drawdown']:.1%}.

**Read this first.** These are the best of 1,226 tries, picked after seeing the results. No strategy has a
Fama-French alpha that clears the luck bar, and the 90% intervals of the top rows overlap SPY's. The top of the
CAGR table is mostly concentration (3-5 stocks) and leverage to the market, with drawdowns of -35% to -55%.

## Paper-trading configuration (`config/paper.json`)

`{cfg['signal']}`, top {cfg['top_n']}, monthly, ${cfg['capital']:,.0f}: chosen on 2026-10-22 as the best
risk-adjusted option that is not concentrated in a handful of names (a top-10 portfolio, low turnover).

{table(chosen)}

## By return (CAGR)

{table(df.sort_values('cagr', ascending=False))}

## By Sharpe ratio (return per unit of risk)

{table(df.sort_values('sharpe', ascending=False))}
"""
    Path("results/ranking.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
