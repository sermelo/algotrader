"""Diagnostics of the merger-arbitrage deals held (not part of the pre-registered test).

Reads results/merger/merger_arb_deals.csv and deals.csv; writes results/merger/deal_check.md: deals by how they
ended (price series ended = completed or data end; termination 8-K; 540-day limit), the exit price against the
offer for the first group (a check that the ticker and offer were read correctly), the worst deals, and returns by form.
"""
import sys
from pathlib import Path

import pandas as pd

out = Path(sys.argv[1] if len(sys.argv) > 1 else "results/merger")
d = pd.read_csv(out / "merger_arb_deals.csv", parse_dates=["day", "exit_x", "exit_y", "entry"])
a = pd.read_csv(out / "deals.csv", parse_dates=["day", "termination"])
d["ticker"] = d["name"].str.split("@").str[0]
d = d.merge(a[["ticker", "day", "offer", "close", "spread", "form", "termination"]], on=["ticker", "day"], how="left")
d["days"] = (d["exit_y"] - d["day"]).dt.days
term = d["exit_x"] == d["termination"]
maxd = ~term & (d["days"] >= 530)
ended = ~term & ~maxd
d["vs_offer"] = d["close"] * (1 + d["return"]) / d["offer"] - 1
lines = ["# Merger arbitrage: deal check (primary run, 20 slots)", "",
         "Generated by `scripts/merger_deal_check.py`; diagnostics, not part of the pre-registered rule. Deal return = "
         "sale proceeds / purchase cost - 1 (base costs). Exit price vs offer is approximated as the decision-day close "
         "x (1 + deal return).", "",
         "| How the deal ended | Deals | Mean return | Median return | Sum of returns |", "|---|---|---|---|---|"]
for lab, m in (("price series ended (deal closed, or data end Mar 2026)", ended), ("termination 8-K", term),
               ("540-day limit", maxd)):
    r = d.loc[m, "return"]
    lines.append(f"| {lab} | {m.sum()} | {r.mean():+.2%} | {r.median():+.2%} | {r.sum():+.2f} |")
q = d.loc[ended, "vs_offer"].quantile([0.05, 0.25, 0.5, 0.75, 0.95])
lines += ["", "Exit price against the offer, series-ended deals: " + ", ".join(f"{k:.0%} {v:+.2%}" for k, v in q.items())
          + f"; {(d.loc[ended, 'vs_offer'] < -0.05).sum()} more than 5% below the offer.", "",
          "Worst 20 deals:", "", "| Deal | Form | Offer | Close at decision | Spread | Days | Return | Termination 8-K |",
          "|---|---|---|---|---|---|---|---|"]
for _, r in d.sort_values("return").head(20).iterrows():
    t = "" if pd.isna(r["termination"]) else f"{r['termination']:%Y-%m-%d}"
    lines.append(f"| `{r['name']}` | {r['form']} | {r['offer']:.2f} | {r['close']:.2f} | {r['spread']:.1%} | {r['days']} | "
                 f"{r['return']:+.1%} | {t} |")
lines += ["", "| Form | Deals | Mean return | Median return |", "|---|---|---|---|"]
for f, g in d.groupby("form"):
    lines.append(f"| {f} | {len(g)} | {g['return'].mean():+.2%} | {g['return'].median():+.2%} |")
lines += ["", f"Spread at the decision close (offer / close - 1): median {d['spread'].median():.2%}, mean {d['spread'].mean():.2%}."]
(out / "deal_check.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
